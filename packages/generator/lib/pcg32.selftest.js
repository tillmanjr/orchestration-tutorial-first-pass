// Differential self-test for PCG32, plus generation of the cross-language
// known-answer vectors.
//
//   node packages/generator/lib/pcg32.selftest.js
//   node packages/generator/lib/pcg32.selftest.js --write-vectors
//
// Two jobs:
//
//   1. Assert the limb implementation and the BigInt reference agree over a
//      large number of draws on every stream we use. Disagreement means the
//      fast path is wrong, and every dataset generated with it is wrong in a
//      way no downstream invariant would catch -- the data would be
//      self-consistent and simply not the specified data.
//
//   2. Emit pcg32.vectors.json: fixed expected outputs that ANY port must
//      reproduce. A Rust or C++ generator is correct when it matches these
//      numbers, not when its output "looks random". Without this, the first
//      real evidence of divergence would be two datasets that hash
//      differently, with no way to localise the fault.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Pcg32, Pcg32Ref, DEFAULT_SEED, STREAM } from './pcg32.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const DRAWS = 200_000;
const BOUNDS = [2, 6, 8, 10, 62, 1000, 0x7fffffff];

let failures = 0;
const fail = (msg) => { console.error(`FAIL  ${msg}`); failures++; };

// --- 1. differential: limb vs BigInt --------------------------------------

for (const [name, stream] of Object.entries(STREAM)) {
  const fast = new Pcg32(DEFAULT_SEED, stream);
  const ref = new Pcg32Ref(DEFAULT_SEED, stream);
  let bad = 0, firstBad = -1;
  for (let i = 0; i < DRAWS; i++) {
    const a = fast.next(), b = ref.next();
    if (a !== b) { if (firstBad < 0) firstBad = i; bad++; }
  }
  if (bad) fail(`stream ${name}: ${bad}/${DRAWS} draws differ, first at index ${firstBad}`);
  else console.log(`ok    stream ${name} (${stream}): ${DRAWS} draws identical`);
}

// bounded() shares the rejection loop, so a divergence here means the two
// implementations consumed a different number of draws -- a subtler fault
// than a wrong value, and one that desynchronises everything after it.
for (const n of BOUNDS) {
  const fast = new Pcg32(DEFAULT_SEED, STREAM.A);
  const ref = new Pcg32Ref(DEFAULT_SEED, STREAM.A);
  let bad = 0;
  for (let i = 0; i < 20_000; i++) if (fast.bounded(n) !== ref.bounded(n)) bad++;
  if (bad) fail(`bounded(${n}): ${bad}/20000 differ`);
  else console.log(`ok    bounded(${n}): 20000 draws identical`);
}

// --- 2. structural checks -------------------------------------------------

// Distinct streams must not produce the same sequence; if they did, the three
// datasets would share randomness and the key-overlap targets would be
// meaningless.
{
  const seqs = Object.values(STREAM).map((s) => {
    const g = new Pcg32(DEFAULT_SEED, s);
    return Array.from({ length: 64 }, () => g.next()).join(',');
  });
  if (new Set(seqs).size !== seqs.length) fail('two streams produced identical sequences');
  else console.log(`ok    ${seqs.length} streams mutually distinct`);
}

// bounded() must never return the bound itself, and must cover the range.
{
  const g = new Pcg32(DEFAULT_SEED, STREAM.A);
  const seen = new Set();
  for (let i = 0; i < 100_000; i++) {
    const v = g.bounded(6);
    if (v < 0 || v > 5) { fail(`bounded(6) returned ${v}`); break; }
    seen.add(v);
  }
  if (seen.size !== 6) fail(`bounded(6) covered only ${seen.size}/6 values`);
  else console.log('ok    bounded(6) in range and fully covering');
}

// --- 3. vectors -----------------------------------------------------------

const vectors = {
  _comment: 'Cross-language known-answer vectors for PCG32 (XSH-RR 64->32). Any port must reproduce these exactly. Generated by pcg32.selftest.js --write-vectors.',
  algorithm: 'PCG32 XSH-RR 64/32',
  multiplier: '6364136223846793005',
  seed: DEFAULT_SEED,
  streams: {},
};
for (const [name, stream] of Object.entries(STREAM)) {
  const g = new Pcg32(DEFAULT_SEED, stream);
  const first16 = Array.from({ length: 16 }, () => g.next());
  for (let i = 16; i < 10_000; i++) g.next();
  const at10k = g.next();
  const b = new Pcg32(DEFAULT_SEED, stream);
  vectors.streams[name] = {
    stream,
    first16,
    draw_10000: at10k,
    bounded_6_first16: Array.from({ length: 16 }, () => b.bounded(6)),
  };
}

if (process.argv.includes('--write-vectors')) {
  const p = join(HERE, 'pcg32.vectors.json');
  writeFileSync(p, JSON.stringify(vectors, null, 2) + '\n');
  console.log(`ok    wrote ${p}`);
} else {
  console.log('note  run with --write-vectors to regenerate pcg32.vectors.json');
}

console.log(failures ? `\n${failures} FAILURE(S)` : '\nall checks passed');
process.exit(failures ? 1 : 0);
